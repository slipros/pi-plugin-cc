#!/usr/bin/env bash
# Приём работы pi-исполнителя: дерево после прогона обязано быть чистым.
#
# Зачем: прогон в песочнице оставляет за собой изменённые файлы, которые в
# коммит не попали и работой не являются, — обычно файлы блокировки
# зависимостей, которые правит вложенный тулчейн. Замечают такое случайно, а
# незамеченный хвост уезжает в коммит следующей задачи, где ревьюер видит
# необъяснимый дифф и тратит время на его происхождение.
#
#   pi-accept.sh <repo> [--base <sha>] [--report <путь>] [--allow <путь>]... [--fix] [--qa]
#
# `go.sum`, изменённый тулчейном песочницы, вычищается сам (без --fix и без отказа);
# если в коммите агента менялся `go.mod`, файл считается работой и попадает в хвост.
#
# --base   — хэш HEAD репозитория ДО старта задачи. Проверяет, что поверх него
#            появился коммит: «статус выполнено» у фонового движка совместим с
#            несделанной работой, и без этой сверки приём начинается с чтения
#            отчёта о том, чего нет.
# --report — файл отчёта агента. Проверяет, что он существует и непуст.
# --allow  — файл, изменение которого для ЭТОЙ задачи легитимно и должно было
#            войти в коммит (например `go.sum` в задаче апдейта зависимостей).
#            Такой файл не считается шумом, но и молча не чистится: про него
#            скрипт скажет отдельно — проверь, что он в коммите.
# --fix    — вернуть шумные файлы в исходное состояние (`git checkout --`)
#            и удалить платформенные артефакты, оставленные контейнером.
#            Без флага скрипт только сообщает: решение за супервизором.
# --qa     — приём QA-прогона, у которого «дефект найден» — успех, а не сбой.
#            Такой агент по построению завершается БЕЗ коммита, оставляя в дереве
#            красный тест как воспроизведение: он и есть результат. Правила
#            смягчаются ровно на это: отсутствие коммита — не отказ, а тестовые
#            пути не считаются хвостом (и `--fix` их не трогает — иначе штатная
#            команда приёма уничтожает единственное доказательство дефекта).
#            Прод-пути хвостом остаются: QA их не пишет вовсе.
#
# Выход: 0 — дерево чистое (или шум вычищен `--fix`); 1 — есть хвост;
#        2 — ошибка вызова.
set -u

usage() { echo "использование: pi-accept.sh <repo> [--base <sha>] [--report <путь>] [--allow <путь>]... [--fix] [--qa]" >&2; exit 2; }

REPO="${1:-}"; shift 2>/dev/null || usage
[ -n "$REPO" ] || usage
# Не `-d "$REPO/.git"`: в git worktree `.git` — ФАЙЛ с указателем gitdir, и
# проверка на каталог отвергала бы всю работу, сделанную в режиме B.
git -C "$REPO" rev-parse --git-dir >/dev/null 2>&1 || { echo "не git-репозиторий: $REPO" >&2; exit 2; }
REPO=$(cd "$REPO" && pwd)

ALLOW=""; FIX=0; BASE=""; REPORT=""; QA=0; NO_COMMIT=0
while [ $# -gt 0 ]; do
  case "$1" in
    --allow)  ALLOW="$ALLOW ${2:-}"; shift 2 ;;
    --base)   BASE="${2:-}"; shift 2 ;;
    --report) REPORT="${2:-}"; shift 2 ;;
    --fix)    FIX=1; shift ;;
    --qa)     QA=1; shift ;;
    *)        echo "неизвестный аргумент: $1" >&2; usage ;;
  esac
done

rc=0

# --- Работа вообще сдана? -----------------------------------------------------
# Движок фонового исполнителя закрывает прогон штатным «готово» и тогда, когда
# модель оборвалась на полуслове: усечённый вызов инструмента отбрасывается,
# текстовая часть ответа становится финальной, а статус остаётся «выполнено».
# Поэтому приём начинается не с чтения отчёта, а с двух механических фактов —
# коммит поверх точки старта есть, файл отчёта существует. У субагентов харнесса
# это держит хук сдачи; у внешнего движка своего гарда нет, и класс «зелёный
# статус при несделанной работе» проходит насквозь.

if [ -n "$BASE" ]; then
  if ! git -C "$REPO" cat-file -e "$BASE^{commit}" 2>/dev/null; then
    echo "BASE $BASE не резолвится в $REPO — сверять не с чем" >&2; exit 2
  fi
  if [ "$(git -C "$REPO" rev-parse HEAD)" = "$(git -C "$REPO" rev-parse "$BASE")" ]; then
    if [ "$QA" -eq 1 ]; then
      echo "коммита нет — для QA-прогона это законный исход: дефект найден, красный тест остаётся в дереве."
      echo "  сверь по отчёту: «дефекты» непусты. Пусты и коммита нет — работа НЕ сдана, дозаход продолжением сессии."
    else
      echo "КОММИТА НЕТ: HEAD совпадает с BASE ($BASE) — работа не сдана, что бы ни говорил статус прогона."
      echo "  дозаход делай продолжением сессии агента (контекст цел), а не задачей заново."
      NO_COMMIT=1
      rc=1
    fi
  else
    echo "коммитов поверх BASE: $(git -C "$REPO" rev-list --count "$BASE..HEAD")"
  fi
fi

if [ -n "$REPORT" ] && [ ! -s "$REPORT" ]; then
  echo "ОТЧЁТА НЕТ (или пуст): $REPORT"
  echo "  отчёт пишет агент; составленный супервизором задним числом описывает не работу, а догадку о ней."
  rc=1
fi

# Только отслеживаемые изменения: untracked-файлы — это обычно документы эпика
# и отчёты, они живут вне коммитов сознательно.
changed=$(git -C "$REPO" diff --name-only HEAD --ignore-cr-at-eol)

# --- Платформенные артефакты из контейнера ------------------------------------
#
# Прогон в песочнице ставит зависимости под linux/amd64 прямо в рабочее дерево:
# .venv с ELF-интерпретатором, node_modules с нативными модулями, go.work с
# контейнерными путями. На macOS-хосте такой каталог не просто бесполезен — он
# перехватывает хостовый тулчейн: `python` из .venv не запускается, `npm test`
# падает на чужом бинаре. В git этого не видно (каталоги игнорируются), поэтому
# смотрим на сами файлы, и не на факт их существования — у фронтенда node_modules
# законно лежит на хосте, — а на платформу: ELF там, где ждут Mach-O.
alien=""
is_elf() { [ -f "$1" ] && [ "$(head -c 4 "$1" 2>/dev/null | od -An -c | tr -d ' \n')" = "177ELF" ]; }
for probe in .venv/bin/python .venv/bin/python3; do
  is_elf "$REPO/$probe" && { alien="$alien .venv"; break; }
done
if [ -d "$REPO/node_modules" ]; then
  native=$(find "$REPO/node_modules" -name '*.node' -type f 2>/dev/null | head -3)
  for f in $native; do is_elf "$f" && { alien="$alien node_modules"; break; }; done
fi
if [ -f "$REPO/go.work" ] && grep -q '/workspace/' "$REPO/go.work" 2>/dev/null; then
  alien="$alien go.work"
fi

if [ -n "$alien" ]; then
  echo "АРТЕФАКТЫ КОНТЕЙНЕРА В ДЕРЕВЕ (собраны под linux, хостовый тулчейн об них спотыкается):$alien"
  if [ "$FIX" -eq 1 ]; then
    for a in $alien; do rm -rf "${REPO:?}/$a" && echo "  удалено: $a"; done
  else
    echo "  удалить: (cd $REPO && rm -rf$alien)"
    echo "  либо перезапустить с --fix"
    rc=1
  fi
fi

if [ -z "$changed" ]; then
  # Артефакты контейнера уже названы выше и в git не видны: сказать «дерево
  # чистое» после них значило бы отменить собственную находку.
  [ -n "$alien" ] && echo "отслеживаемых изменений нет — но выше названы артефакты контейнера" \
                  || echo "дерево чистое: хвостов после прогона нет"
  exit "$rc"
fi

# Тестовый путь у QA-прогона — не хвост, а deliverable: красный тест, оставленный
# в дереве, воспроизводит найденный дефект и в ветку не идёт по построению.
is_test_path() {
  case "$1" in
    *_test.go|*_test.py|*.test.ts|*.test.js|*.spec.ts|*.spec.js|*_spec.rb|*Test.java|*Tests.cs) return 0 ;;
    */tests/*|tests/*|*/testdata/*|testdata/*|*/e2e/*|e2e/*|*/integration/*|integration/*) return 0 ;;
    *docker-compose*.test.*|*compose.test.*) return 0 ;;
  esac
  return 1
}

# Хвост тулинга песочницы: файл меняет не задача, а линтерный тулчейн прогона
# (`go.sum` прирастает хешами инструментов). Чистится сам, без --fix и без отказа —
# иначе супервизор делает это руками после каждого прогона. Но если BASE задан и в
# коммите агента менялся манифест зависимостей, тот же файл — часть работы: чистка
# сломала бы сборку, поэтому такой случай остаётся обычным хвостом.
is_toolchain_noise() {
  case "$1" in go.sum|*/go.sum) ;; *) return 1 ;; esac
  [ -n "$BASE" ] || return 0
  git -C "$REPO" diff --name-only "$BASE..HEAD" | grep -qE '(^|/)go\.mod$' && return 1
  return 0
}

noise=""; expected=""; kept=""; toolchain=""
for f in $changed; do
  hit=0
  for a in $ALLOW; do [ "$f" = "$a" ] && hit=1; done
  if [ "$hit" -eq 1 ]; then expected="$expected $f"
  elif [ "$QA" -eq 1 ] && is_test_path "$f"; then kept="$kept $f"
  elif is_toolchain_noise "$f"; then toolchain="$toolchain $f"
  else noise="$noise $f"; fi
done

# Без коммита поверх BASE у прогона нет второго выхода: всё, что он сделал,
# лежит в рабочем дереве. Называть это хвостом и предлагать `git checkout --`
# значит предлагать стереть саму работу — а именно так выглядит прогон, чей
# коммит отклонил гейт (например QA-хук на прод-коде). Поэтому в этом состоянии
# ничего не чистится: ни автоматически, ни по --fix.
if [ "$NO_COMMIT" -eq 1 ] && [ -n "$changed" ]; then
  echo "НЕСОХРАНЁННАЯ РАБОТА В ДЕРЕВЕ (коммита поверх BASE нет):$changed"
  echo "  это не хвост: без коммита рабочее дерево — единственный результат прогона."
  echo "  разберись, почему коммит не состоялся (гейт хука, упавший линтер, оборванный прогон),"
  echo "  и доведи до коммита дозаходом; git checkout -- здесь стирает работу."
  exit 1
fi

if [ -n "$toolchain" ]; then
  # shellcheck disable=SC2086
  if git -C "$REPO" checkout -- $toolchain 2>/dev/null; then
    echo "хвост тулинга песочницы вычищен автоматически:$toolchain"
  else
    echo "ХВОСТ ТУЛИНГА не вычистился:$toolchain"; rc=1
  fi
fi

if [ -n "$kept" ]; then
  echo "тестовые файлы оставлены в дереве (QA-прогон, воспроизведение дефекта):$kept"
  echo "  это результат, а не хвост: --fix их не трогает. Дефект разобран — убирает супервизор."
fi

if [ -n "$expected" ]; then
  echo "изменения, заявленные как часть задачи:$expected"
  echo "  проверь, что они вошли в коммит агента — иначе работа сдана наполовину."
  rc=1
fi

if [ -n "$noise" ]; then
  echo "ХВОСТ ПОСЛЕ ПРОГОНА (в коммит не вошёл, работой не является):$noise"
  if [ "$FIX" -eq 1 ]; then
    # shellcheck disable=SC2086
    git -C "$REPO" checkout -- $noise && echo "  вычищено (git checkout --)"
  else
    echo "  вычистить: git -C $REPO checkout --$noise"
    echo "  либо перезапустить с --fix"
    rc=1
  fi
fi

exit $rc
